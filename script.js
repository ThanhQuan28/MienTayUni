function showAutoToast(message, type = "success", duration = 5000) {
  let toastContainer = document.getElementById("toast-container");
  if (!toastContainer) {
    toastContainer = document.createElement("div");
    toastContainer.id = "toast-container";
    toastContainer.className =
      "fixed bottom-5 right-5 z-50 flex flex-col space-y-2";
    document.body.appendChild(toastContainer);
  }
  const toast = document.createElement("div");
  const bgColor = type === "success" ? "bg-emerald-600" : "bg-blue-600";
  toast.className = `${bgColor} text-white font-bold text-sm px-5 py-3 rounded-2xl shadow-2xl flex items-center space-x-2 transition-all duration-300 transform translate-y-2 opacity-0`;
  toast.innerHTML = `<i class="fa-solid fa-circle-info"></i><span>${message}</span>`;
  toastContainer.appendChild(toast);
  setTimeout(() => {
    toast.classList.remove("translate-y-2", "opacity-0");
  }, 10);
  setTimeout(() => {
    toast.classList.add("opacity-0", "translate-y-2");
    setTimeout(() => toast.remove(), 300);
  }, duration);
}

