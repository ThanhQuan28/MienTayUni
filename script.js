// Logic Tỉnh -> Chọn Trường
function onProvinceChange() {
  const tinhSelected = document.getElementById("filter-tinh").value;
  const selectTruong = document.getElementById("filter-truong");
  let availableSchools = [];
  if (tinhSelected) {
    availableSchools = database2026.filter(
      (item) => item.province === tinhSelected,
    );
  } else {
    availableSchools = database2026;
  }
  const uniqueSchools = Array.from(
    new Set(availableSchools.map((a) => a.schoolCode)),
  ).map((code) => {
    return availableSchools.find((a) => a.schoolCode === code);
  });
  selectTruong.innerHTML = `<option value="">Tất cả các trường</option>`;
  uniqueSchools.forEach((school) => {
    selectTruong.innerHTML += `<option value="${school.schoolCode}">${school.schoolName} (${school.schoolCode})</option>`;
  });
  filterData();
}

// Logic Lọc & Hiển thị Trường/Ngành
function filterData() {
  const tinhEl = document.getElementById("filter-tinh");
  const truongEl = document.getElementById("filter-truong");
  const searchEl = document.getElementById("filter-search");
  if (!tinhEl || !truongEl || !searchEl) return;
  const tinh = tinhEl.value;
  const truong = truongEl.value;
  const searchRaw = searchEl.value.trim();
  const searchNormalized = normalizeYiSearch(searchRaw);
  const filteredData = database2026.filter((item) => {
    const matchTinh = !tinh || item.province === tinh;
    const matchTruong = !truong || item.schoolCode === truong;
    const majorNorm = normalizeYiSearch(item.major);
    const codeNorm = normalizeYiSearch(item.majorCode);
    const matchSearch =
      !searchRaw ||
      majorNorm.includes(searchNormalized) ||
      codeNorm.includes(searchNormalized);
    return matchTinh && matchTruong && matchSearch;
  });
  const schoolsMap = {};
  filteredData.forEach((item) => {
    if (!schoolsMap[item.schoolCode]) {
      schoolsMap[item.schoolCode] = {
        schoolCode: item.schoolCode,
        schoolName: item.schoolName,
        province: item.province,
        majors: [],
      };
    }
    schoolsMap[item.schoolCode].majors.push(item);
  });
  const schoolsList = Object.values(schoolsMap);
  renderSchoolCards(schoolsList, Boolean(searchRaw || truong));
}

// Toggle mở rộng / thu hẹp danh sách ngành của trường
function toggleExpandSchool(schoolCode) {
  expandedSchools[schoolCode] = !expandedSchools[schoolCode];
  filterData();
}

