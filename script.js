// Hàm chuẩn hóa chuỗi loại bỏ biệt lập chính tả giữa 'y' và 'i'
function normalizeYiSearch(text) {
  if (!text) return "";
  return text
    .toLowerCase()
    .replace(/y/g, "i")
    .normalize("NFD")
    .replace(/[\u0300-\u036f]/g, "");
}

